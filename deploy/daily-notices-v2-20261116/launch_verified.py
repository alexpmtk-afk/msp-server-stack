import gzip,hashlib,io,json,os,pathlib,subprocess,sys,tarfile,tempfile
assert os.geteuid()==0,"Run in Linux root console"
os.umask(0o077)
stage=pathlib.Path(tempfile.mkdtemp(prefix="msp-daily-notices-v2.",dir="/var/lib"))
with pathlib.Path('/home/hermes/workspace/daily-notices-v2-20261116/daily-notices-v2.tar.gz').open("rb") as f:raw=f.read(16000001)
assert len(raw)<16000000 and hashlib.sha256(raw).hexdigest()=='d43e089400436ada1ef6b0ec6b566d25c8980053800f581fd41e862a5008aa0c',"Archive hash mismatch"
(stage/"package.tar.gz").write_bytes(raw)
with tarfile.open(fileobj=io.BytesIO(raw),mode="r:gz") as t:
 members=t.getmembers();names=[m.name for m in members]
 assert len(names)==len(set(names)) and len(names)<200
 assert all(m.isfile() and m.mode==0o644 and m.size<4000000 and not pathlib.PurePosixPath(m.name).is_absolute() and ".." not in pathlib.PurePosixPath(m.name).parts for m in members)
 data={m.name:t.extractfile(m).read() for m in members}
 assert sum(map(len,data.values()))<16000000
 assert hashlib.sha256(data["MANIFEST.json"]).hexdigest()=='1213081eb87603ebbfa3c418ec57f90f2cc8036995bfd3891bfb80d465045e5a'
